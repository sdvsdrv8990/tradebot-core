/* ==========================================================================
 *  tb/core/marker.h — быстрая диагностика printf-маркерами.
 *
 *  Ручной разбор состояния ядра ненадёжен: при живом поиске причины (вроде
 *  неинициализированной ошибки или «breaker открылся в t=2, а пробу ждут в
 *  t=100») первым делом нужны короткие однозначные метки на пути исполнения.
 *  TB_MARK() расставляет их в ключевых точках компонентов (реестр событий,
 *  планировщик, ядро) и в пользовательском коде.
 *
 *  Свойства:
 *   - в release-сборке вырождается в ((void)0) — нулевая цена;
 *   - включается определением TB_EVENT_MARKERS=1 (файл, цель сборки или
 *     опция CMake TB_ENABLE_MARKERS / цель make markers);
 *   - вывод — stderr, построчно: "[mark файл:строка] сообщение";
 *   - форматная строка проходит проверку компилятора (-Wformat).
 *
 *  Маркер — не лог: лог пишется всегда и структурированно (tb/core/log),
 *  маркер — временный инструмент отладки конкретного прогона.
 * ========================================================================== */
#ifndef TB_CORE_MARKER_H
#define TB_CORE_MARKER_H

#ifndef TB_EVENT_MARKERS
#define TB_EVENT_MARKERS 0
#endif

#if TB_EVENT_MARKERS
#include <stdio.h>
#define TB_MARK(...)                                            \
    do {                                                        \
        fprintf(stderr, "[mark %s:%d] ", __FILE__, __LINE__);   \
        fprintf(stderr, __VA_ARGS__);                           \
        fputc('\n', stderr);                                    \
    } while (0)
#else
#define TB_MARK(...) ((void)0)
#endif

#endif /* TB_CORE_MARKER_H */
